# game/clock.py — นาฬิกาเดียวของทั้งเกม
#
# ทุกอย่างที่เกี่ยวกับตำแหน่งอุกกาบาตอ้างอิงนาฬิกานี้ตัวเดียว
# client แต่ละเครื่องหา offset ของตัวเองเทียบนาฬิกานี้ตอน connect (ดู net.js)
# แล้วคำนวณตำแหน่งเองได้ตรงกันเป๊ะโดยไม่ต้องรับตำแหน่งจาก server ทุก frame
#
# ใช้ perf_counter ไม่ใช่ time.time() เพราะ time.time() กระโดดได้ถ้า OS sync เวลา
# ระหว่างเกม แล้วอุกกาบาตทั้งฟ้าจะเทเลพอร์ตพร้อมกัน

import time

_T0 = time.perf_counter()


def now_ms() -> float:
    """มิลลิวินาทีตั้งแต่ server เริ่ม — เพิ่มขึ้นอย่างเดียว ไม่มีกระโดด"""
    return (time.perf_counter() - _T0) * 1000.0
